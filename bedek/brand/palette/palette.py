# -*- coding: utf-8 -*-
"""
Palette directions for the TACT Bedek marketing brand.

Specified in OKLCH, compiled to hex. Why OKLCH: its L is *perceived*
lightness, so two colours that share an L carry equal visual weight even at
different hues -- which is the whole trick behind bridging the emerald app
(H 169) and the indigo app (H 285) without one swamping the other.

Anchors we are bridging between:
    emerald app brand   oklch(0.579 0.113 169)  #0F8F6E
    indigo  app brand   oklch(0.550 0.113 285)  #6B67B0
    TACT steel-blue     oklch(0.340 0.068 256)  #1F3A5F

    python palette.py   -> directions.json (all four) + tokens.css (chosen)
"""
import io, json, os, sys

sys.stdout.reconfigure(encoding="utf-8")  # Hebrew dies on cp1252 otherwise

# Paths resolve against this file, never the caller's cwd -- these are run as
# `python brand/palette/palette.py` from the brand root.
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from oklch import oklch

EMERALD_H, INDIGO_H, STEEL_H = 169.0, 285.0, 256.0

# Chosen 2026-08-25. The other three stay in this file on purpose: they are the
# record of what was considered, and contrast.py keeps gating all four, so a
# later edit to the shared ramp() cannot quietly break one we might return to.
CHOSEN = "bridge"


def ramp(bh, bc, bl, accent, canvas_h, name, title, rationale, note):
    """One direction. `accent` is (L, C, H) for the CTA colour."""
    al, ac, ah = accent
    return {
        "name": name, "title": title, "rationale": rationale, "note": note,
        "colors": {
            # identity -- the only large filled areas of colour
            "brand":      oklch(bl,        bc,        bh),
            "brandDeep":  oklch(bl - 0.08, bc,        bh),
            "brandInk":   oklch(0.30,      bc * 0.75, bh),
            "brandSoft":  oklch(0.955,     bc * 0.22, bh),
            # the one action you want taken
            "accent":     oklch(al,        ac,        ah),
            "accentDeep": oklch(al - 0.10, ac,        ah),
            "accentSoft": oklch(0.955,     ac * 0.22, ah),
            # grounds
            "canvas":     oklch(0.982, 0.006, canvas_h),
            "surface":    "#FFFFFF",
            "mist":       oklch(0.958, 0.010, canvas_h),
            "border":     oklch(0.905, 0.012, canvas_h),
            # text -- never pure black, always tinted toward the brand hue
            "inkStrong":  oklch(0.245, 0.022, bh),
            "inkSoft":    oklch(0.470, 0.020, bh),
            "inkFaint":   oklch(0.600, 0.016, bh),
            # the two products, always shown in their real app colours
            "appUser":     oklch(0.550, 0.113, INDIGO_H),
            "appCustomer": oklch(0.579, 0.113, EMERALD_H),
        },
    }


def tokens_css(d):
    """The chosen direction, compiled for the site. Never hand-edit the output."""
    rows = "\n".join("  --{}: {};".format(k, v) for k, v in d["colors"].items())
    return (
        "/* GENERATED by brand/palette/palette.py -- do not hand-edit.\n"
        "   Direction: {} ({}). Regenerate with `python palette.py`.\n"
        "   Every pair is gated by contrast.py against WCAG AA. */\n"
        ":root {{\n{}\n}}\n"
    ).format(d["title"], d["name"], rows)


