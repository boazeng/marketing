def chosen():
    return next(d for d in DIRECTIONS if d["name"] == CHOSEN)


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "directions.json")
    io.open(out, "w", encoding="utf-8").write(
        json.dumps(DIRECTIONS, ensure_ascii=False, indent=2))
    io.open(os.path.join(HERE, "tokens.css"), "w", encoding="utf-8").write(tokens_css(chosen()))

    for d in DIRECTIONS:
        c = d["colors"]
        mark = "   <-- CHOSEN" if d["name"] == CHOSEN else ""
        print("{:10} brand {}  accent {}  canvas {}{}".format(
            d["name"], c["brand"], c["accent"], c["canvas"], mark))
    print("\nwrote directions.json + tokens.css")
